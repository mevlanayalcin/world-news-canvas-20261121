def project(lon, lat, box, lon0=-132.0, lon1=180.0, lat0=-50.0, lat1=74.0):
    """Equirectangular projection into box=(x, y, w, h)."""
    x, y, w, h = box
    px = x + (lon - lon0) / (lon1 - lon0) * w
    py = y + (lat1 - lat) / (lat1 - lat0) * h
    return px, py
